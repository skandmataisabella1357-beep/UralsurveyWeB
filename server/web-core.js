'use strict';
// Точка входа службы uralsurvey-web на сервере (rtk.ntrip.host).
// Служба systemd запускает именно этот файл и задаёт адрес и порт страницы в переменных
// URAL_HOST и URAL_PORT; nginx отдаёт этот порт наружу по HTTPS.
//
// Сейчас здесь поднимается сервер с тестовой сетью: три службы и 50 синтетических баз.
// Всё, кроме страницы состояния, слушает только 127.0.0.1 — настоящих станций и роверов нет.
// Когда сервер перейдёт на настоящие станции, этот файл станет запускать server/run.js
// с рабочими настройками.

const { main } = require('./testnet/run');

if ((process.env.URAL_HOST || '127.0.0.1') !== '127.0.0.1') {
  console.error('Страница состояния отдаётся только через nginx: URAL_HOST должен быть 127.0.0.1.');
  process.exit(1);
}
main(['--control-port', process.env.URAL_PORT || '8110']);
